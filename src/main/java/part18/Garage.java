public class Garage {

        // This method parks my car
        void park(Car car) {

            // This prints which car is parked
            System.out.println("The " + car.name + " is parked in the garage");
        }

        // This method makes my car leave
        void leave(Car car) {

            // This prints which car left
            System.out.println("The " + car.name + " left the garage");
        }
    }


